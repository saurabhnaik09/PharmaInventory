import type { Medicine, StockStatus } from '../../types';

// Helper: compute stock status
function computeStatus(currentStock: number, minimumStock: number, expiryDate: string): StockStatus {
  const today = new Date();
  const expiry = new Date(expiryDate);
  const daysToExpiry = Math.floor((expiry.getTime() - today.getTime()) / (1000 * 60 * 60 * 24));

  if (currentStock === 0) return 'out_of_stock';
  if (currentStock <= minimumStock) return 'low_stock';
  if (daysToExpiry <= 90) return 'expiring_soon';
  return 'in_stock';
}

